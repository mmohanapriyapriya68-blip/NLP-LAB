
# Noun Morphology
noun = "child"

print("Noun Morphology:")
print("Singular:", noun)
print("Plural:", noun + "ren")
print("Adjective:", noun + "ish")

# Verb Morphology
verb = "play"

print("\nVerb Morphology:")
print("Base:", verb)
print("Past:", verb + "ed")
print("Present:", verb + "s")
print("Participle:", verb + "ing")
